def norm_name(s):
    s = unicodedata.normalize('NFKC', str(s))
    s = re.sub(r'[\u200e\u2063\u200f\u202a\u200b]', '', s)
    s = re.sub(r'\s+via\s+@\S+', '', s)
    s = re.sub(r'\s+\d{2}\.\d{2}\.\d{4}\s+\d{2}:\d{2}:\d{2}.*$', '', s).strip()
    return s

