stats = defaultdict(lambda: {'msgs':0,'ru_ment':0,'pro':0,'anti':0,
    'pro_ex':[],'anti_ex':[],'for_':defaultdict(int),'for_ex':defaultdict(list)})

for m in data:
    a = norm_name(m.get('name',''))
    if a not in user_set: continue
    t = m.get('text')
    if isinstance(t,list): t=''.join(x if isinstance(x,str) else x.get('text','') for x in t)
    if not t or not isinstance(t,str): continue
    tl = t.lower()
    s = stats[a]; s['msgs']+=1
    if any(re.search(p,tl) for p in PRO_RU):
        s['pro']+=1
        if len(s['pro_ex'])<4: s['pro_ex'].append(t[:160])
    if any(re.search(p,tl) for p in ANTI_RU):
        s['anti']+=1
        if len(s['anti_ex'])<4: s['anti_ex'].append(t[:160])
    if any(re.search(p,tl) for p in RU_NEUTRAL):
        s['ru_ment']+=1
    for c,p in FOREIGN.items():
        if re.search(p,tl):
            s['for_'][c]+=1
            if len(s['for_ex'][c])<3: s['for_ex'][c].append(t[:160])

res=[]
for name,s in stats.items():
    s=dict(s); s['for_']=dict(s['for_']); s['for_ex']={k:v for k,v in s['for_ex'].items()}
    s['name']=name; res.append(s)
json.dump(res, open('/workspace/patriot_raw.json','w',encoding='utf-8'), ensure_ascii=False, indent=1)

print(f"{'name':24}{'msgs':>7}{'ru%':>6}{'pro':>5}{'anti':>5}  top_foreign")
